def build(document: dict) -> str:
    """Return the HTML report for a JSON report ``document``."""
    data = json.dumps(document, ensure_ascii=False)
    # Make the embedded JSON safe inside a <script> element.
    data = data.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    version = str(document.get("version", ""))
    return _TEMPLATE.replace("__VERSION__", version).replace("__DATA__", data)
